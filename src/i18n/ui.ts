export const ui = { th, en } satisfies L<UiStrings>;

/** The interface strings for one language. */
export function t(lang: Locale): UiStrings {
  return ui[lang];
}

/**
 * Fills the `{placeholders}` of a pattern: `fill(ui.patterns.callOn, { phone })`.
 * A placeholder with no value is a bug in the caller, so it throws instead of printing braces to a guest.
 */
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, name: string) => {
    const value = values[name];
    if (value === undefined) throw new Error(`fill(): no value for {${name}} in "${template}"`);
    return String(value);
  });
}
